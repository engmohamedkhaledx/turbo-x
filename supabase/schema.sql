-- ---------------------------------------------------------------------
-- 1. TABLES
-- ---------------------------------------------------------------------

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  role text not null check (role in ('student', 'admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.quizzes (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  published boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.questions (
  id bigint generated by default as identity primary key,
  quiz_id bigint not null references public.quizzes(id) on delete cascade,
  question_text text not null,
  options jsonb not null,
  correct_answer text not null,
  points integer not null default 1
);

create table if not exists public.quiz_attempts (
  id bigint generated by default as identity primary key,
  quiz_id bigint not null references public.quizzes(id) on delete cascade,
  student_id uuid not null references public.profiles(id) on delete cascade,
  score numeric not null default 0,
  total_points numeric not null default 0,
  percentage numeric not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.quiz_attempt_answers (
  id bigint generated by default as identity primary key,
  attempt_id bigint not null
    constraint quiz_attempt_answers_attempt_id_fkey
    references public.quiz_attempts(id) on delete cascade,
  question_id bigint
    constraint quiz_attempt_answers_question_id_fkey
    references public.questions(id) on delete set null,
  student_answer text,
  is_correct boolean not null,
  points_earned numeric not null default 0,
  question_text text not null,
  correct_answer text not null,
  possible_points numeric not null,
  question_order integer not null,
  created_at timestamptz not null default now()
);

create table if not exists public.assignments (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  file_path text,
  due_date timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.submissions (
  id bigint generated by default as identity primary key,
  assignment_id bigint not null references public.assignments(id) on delete cascade,
  student_id uuid not null references public.profiles(id) on delete cascade,
  file_path text,
  grade numeric,
  feedback text,
  created_at timestamptz not null default now(),
  graded_at timestamptz,
  graded_by uuid references public.profiles(id) on delete set null
);

-- Keep existing databases compatible with the grading workflow.
alter table public.submissions
  add column if not exists graded_at timestamptz;

alter table public.submissions
  add column if not exists graded_by uuid references public.profiles(id) on delete set null;

-- Helpful indexes
create index if not exists idx_questions_quiz_id on public.questions(quiz_id);
create index if not exists idx_quiz_attempts_student_id on public.quiz_attempts(student_id);
create index if not exists idx_quiz_attempts_quiz_id on public.quiz_attempts(quiz_id);
