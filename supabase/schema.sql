create index if not exists idx_submissions_student_id on public.submissions(student_id);
create index if not exists idx_submissions_assignment_id on public.submissions(assignment_id);

-- ---------------------------------------------------------------------
-- 2. SECURE ADMIN HELPER FUNCTION
-- ---------------------------------------------------------------------
-- SECURITY DEFINER + fixed search_path so it always resolves
-- public.profiles regardless of caller's search_path, and runs with the
-- privileges of the function owner so it can read profiles even though
-- RLS is enabled on that table.

create or replace function public.is_admin()
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (
    select 1
    from public.profiles
    where id = auth.uid()
      and role = 'admin'
  );
$$;

grant execute on function public.is_admin() to authenticated;

