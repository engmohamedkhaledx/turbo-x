-- Save the aggregate attempt and its ordered, immutable answer snapshots atomically.
create or replace function public.submit_quiz_attempt(
  p_quiz_id bigint,
  p_student_id uuid,
  p_answers jsonb
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_attempt_id bigint;
  v_question record;
  v_question_order integer := 0;
  v_student_answer text;
  v_is_correct boolean;
  v_points_earned numeric;
  v_score numeric := 0;
  v_total_points numeric := 0;
  v_percentage numeric := 0;
begin
  if auth.uid() is null or auth.uid() is distinct from p_student_id then
    raise exception 'Students may only submit attempts for themselves.'
      using errcode = '42501';
  end if;

  if jsonb_typeof(p_answers) is distinct from 'object' then
    raise exception 'Quiz answers must be provided as an object.'
      using errcode = '22023';
  end if;

  if not exists (
    select 1 from public.quizzes
    where id = p_quiz_id and published = true
  ) then
    raise exception 'Quiz not found or not available.'
      using errcode = '23503';
  end if;

  insert into public.quiz_attempts (
    quiz_id, student_id, score, total_points, percentage
  )
  values (p_quiz_id, p_student_id, 0, 0, 0)
  returning id into v_attempt_id;

  for v_question in
    select id, question_text, correct_answer, points
    from public.questions
    where quiz_id = p_quiz_id
    order by id asc
  loop
    v_question_order := v_question_order + 1;
    v_student_answer := p_answers ->> v_question.id::text;
    v_is_correct :=
      v_student_answer is not null
      and v_student_answer = v_question.correct_answer;
    v_points_earned :=
      case when v_is_correct then v_question.points else 0 end;

    v_total_points := v_total_points + v_question.points;
    v_score := v_score + v_points_earned;

    insert into public.quiz_attempt_answers (
      attempt_id,
      question_id,
      student_answer,
      is_correct,
      points_earned,
      question_text,
      correct_answer,
      possible_points,
      question_order
    )
    values (
      v_attempt_id,
      v_question.id,
      v_student_answer,
      v_is_correct,
      v_points_earned,
      v_question.question_text,
      v_question.correct_answer,
      v_question.points,
      v_question_order
    );
  end loop;

  if v_total_points > 0 then
    v_percentage := round((v_score / v_total_points) * 100);
  end if;

  update public.quiz_attempts
  set score = v_score,
      total_points = v_total_points,
      percentage = v_percentage
  where id = v_attempt_id;

  return v_attempt_id;
end;
$$;

revoke all on function public.submit_quiz_attempt(bigint, uuid, jsonb) from public, anon;
grant execute on function public.submit_quiz_attempt(bigint, uuid, jsonb) to authenticated;

